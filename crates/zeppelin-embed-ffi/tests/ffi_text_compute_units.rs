#![cfg(all(feature = "text", target_os = "macos"))]

mod common;

use std::process::Command;
use zeppelin_embed_ffi::*;

#[test]
fn text_observed_compute_units_loads_tiny_coreml_plan() {
    if !compute_plan_available() {
        return;
    }
    let root = tempfile::tempdir().expect("CoreML compiler directory");
    let source = root.path().join("tiny.mlmodel");
    std::fs::write(
        &source,
        include_bytes!("../../zeppelin-embed-text/tests/fixtures/ze115/tiny.mlmodel"),
    )
    .expect("write portable model");
    let output = Command::new("xcrun")
        .args(["coremlcompiler", "compile"])
        .arg(&source)
        .arg(root.path())
        .output()
        .expect("run platform CoreML compiler");
    assert!(
        output.status.success(),
        "CoreML compilation failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let model = root.path().join("tiny.mlmodelc");
    assert!(model.is_dir());
    run_child("present", model.as_os_str());
}

#[test]
fn text_observed_compute_units_is_absent_without_coreml() {
    run_child("absent", std::ffi::OsStr::new("off"));
}

fn run_child(mode: &str, model: &std::ffi::OsStr) {
    let output = Command::new(std::env::current_exe().expect("test executable"))
        .args([
            "--exact",
            "text_observed_compute_units_child",
            "--nocapture",
        ])
        .env("ZE521_COMPUTE_UNITS_CHILD", mode)
        .env("ZE_QUERY_COREML", model)
        .output()
        .expect("isolated CoreML model discovery");
    assert!(
        output.status.success(),
        "compute units child failed:\n{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(String::from_utf8_lossy(&output.stdout).contains("ZE521 compute units checked"));
}

#[test]
fn text_observed_compute_units_child() {
    let Some(mode) = std::env::var_os("ZE521_COMPUTE_UNITS_CHILD") else {
        return;
    };
    let present = mode == "present";
    let store = if present {
        let root = tempfile::tempdir().expect("store root");
        let model = root.path().join("document.zem");
        // Generated by the text crate's common::write_fixture_bundle with
        // FixtureTower::document("fixture-symmetric"), max_tokens = 2.
        // Reuse its symmetric bundle without importing its xxhash dependency.
        std::fs::write(&model, include_bytes!("fixtures/compute_units.zem"))
            .expect("symmetric fixture bundle");
        common::text::TextStore::with_bundle(root, &model)
    } else {
        common::text::TextStore::new()
    };
    // Dirty counts prove the absent response overwrites caller storage.
    let mut out: ZeTextObservedComputeUnits = common::sized_zeroed();
    out.cpu_ops = u64::MAX;
    out.gpu_ops = u64::MAX;
    out.neural_engine_ops = u64::MAX;
    out.other_ops = u64::MAX;
    out.has_observed_compute_units = u32::MAX;
    assert_eq!(
        ze_text_observed_compute_units(store.handle, &mut out),
        ZeErrorCode::ZeOk
    );
    assert_eq!(out.has_observed_compute_units, u32::from(present));
    if present {
        // Like the text contract: this fixture has one op, whose placement
        // under CPU+ANE may vary with hardware and OS.
        assert_eq!(
            out.cpu_ops + out.gpu_ops + out.neural_engine_ops + out.other_ops,
            1
        );
    } else {
        assert_eq!(
            (
                out.cpu_ops,
                out.gpu_ops,
                out.neural_engine_ops,
                out.other_ops
            ),
            (0, 0, 0, 0)
        );
    }
    assert_eq!(out.abi_reserved, 0);
    assert_eq!(out.reserved, 0);
    println!("ZE521 compute units checked");
}

// Same availability check as zeppelin-embed-text/tests/common.
fn compute_plan_available() -> bool {
    let output = Command::new("sw_vers")
        .arg("-productVersion")
        .output()
        .expect("macOS version");
    assert!(output.status.success());
    let version = String::from_utf8(output.stdout).expect("macOS version text");
    let mut components = version.trim().split('.');
    let major: u32 = components
        .next()
        .expect("major version")
        .parse()
        .expect("major number");
    let minor: u32 = components
        .next()
        .expect("minor version")
        .parse()
        .expect("minor number");
    (major, minor) >= (14, 4)
}
