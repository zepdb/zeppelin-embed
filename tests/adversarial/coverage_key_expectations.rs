#[test]
fn namespace_relocation_coverage_keys_are_required() {
    let required = crate::adversarial::campaign::CampaignSpec::for_kind(
        crate::adversarial::campaign::CampaignKind::StorageDurability,
    )
    .all_required_coverage();
    for key in [
        "storage.namespace.whole-root-rename",
        "storage.namespace.whole-root-copy",
        "storage.namespace.detached-root-refusal",
        "storage.namespace.bootstrap-root.clean",
        "storage.namespace.bootstrap-root.fired",
        "storage.namespace.bootstrap-reference.clean",
        "storage.namespace.bootstrap-reference.fired",
        "storage.namespace.enlist-reference.clean",
        "storage.namespace.enlist-reference.fired",
        "storage.namespace.conversion-copy.clean",
        "storage.namespace.conversion-copy.fired",
        "storage.namespace.conversion-copy.can-fire",
        "storage.namespace.conversion-write.clean",
        "storage.namespace.conversion-write.fired",
        "storage.namespace.conversion-write.can-fire",
        "storage.namespace.conversion-file-sync.clean",
        "storage.namespace.conversion-file-sync.fired",
        "storage.namespace.conversion-file-sync.can-fire",
        "storage.namespace.conversion-directory-sync.clean",
        "storage.namespace.conversion-directory-sync.fired",
        "storage.namespace.conversion-directory-sync.can-fire",
        "storage.namespace.conversion-publish.clean",
        "storage.namespace.conversion-publish.fired",
        "storage.namespace.conversion-publish.can-fire",
        "storage.namespace.conversion-parent-sync.clean",
        "storage.namespace.conversion-parent-sync.fired",
        "storage.namespace.conversion-parent-sync.can-fire",
        "storage.namespace.conversion-comparator-rejects-partial",
        "storage.namespace.plain-under-portable-root",
    ] {
        assert!(
            required.iter().any(|candidate| candidate == key),
            "missing namespace relocation key {key}"
        );
    }
    assert_eq!(
        crate::adversarial::storage_durability::NamespaceFault::ALL.len(),
        12
    );
}
