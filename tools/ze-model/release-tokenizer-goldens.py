def source(pack, role, expected=None):
    root = pack / role
    path = root / "tokenizer.json"
    if hashlib.sha256(path.read_bytes()).hexdigest() != (expected or SOURCES[role]):
        raise ValueError(f"{role} tokenizer.json SHA256 differs from the committed release source")
    config = json.loads((root / "config.json").read_text())
    return root, path, config


def pair_contract(pack):
    pair = json.loads((pack / "PAIR.json").read_text())
    for role, digest in SOURCES.items():
        if pair[role]["tokenizer_sha256"] != digest:
            raise ValueError(f"PAIR.json {role} tokenizer_sha256 differs from the pinned release source")
    return pair


def generate(pack, output):
    import tokenizers
    if tokenizers.__version__ != "0.19.1":
        raise ValueError("release oracle requires HF tokenizers == 0.19.1")
    pair = pair_contract(pack)
    lines = ["// Generated by tools/ze-model/release-tokenizer-goldens.py; HF tokenizers 0.19.1.",
             "// max_tokens follows PAIR.json: query 96 (including prefix and specials), document 8192."]
    for role in SOURCES:
        _, path, _ = source(pack, role)
        maximum = int(pair[role]["max_tokens"])
        prefix = "query: " if role == "query" else ""
        tokenizer = tokenizers.Tokenizer.from_file(str(path))
        tokenizer.no_padding()
        tokenizer.enable_truncation(max_length=maximum)
        upper = role.upper()
        lines += [f'pub const {upper}_SHA256: &str = "{SOURCES[role]}";',
                  f"pub const {upper}_MAX_TOKENS: usize = {maximum};",
                  f"pub const {upper}_CASES: &[(&str, &str, usize, &[i32])] = &["]
        for name, text, repeat in CASES:
            ids = tokenizer.encode(prefix + text * repeat).ids
            if name == "truncation":
                assert len(ids) == maximum
            literal = json.dumps(text, ensure_ascii=False)
            # JSON escapes for controls differ from Rust string escapes.
            literal = re.sub(r"\\u([0-9a-fA-F]{4})", r"\\u{\1}", literal)
            lines.append(f'    ("{name}", {literal}, {repeat}, &{ids}),')
        lines.append("];")
    output.write_text("\n".join(lines) + "\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(output)], check=True)


def fixture(pack, output, expected):
    """Use production bake encoders, without loading model weights or running MLX."""
    pair = pair_contract(pack)
    exporter = runpy.run_path(str(Path(__file__).with_name("ze-model")))
    towers = []
    for role in ["document", "query"]:
        root, _, config = source(pack, role, expected[role])
        towers.append(exporter["Tower"](
            role=int(role == "query"), model_id=role, root=root,
            prefix="query: " if role == "query" else "", config=config,
            pooling=2, architecture=3 if role == "query" else 2, dense_out=0, tensors=(),
            weights_digest=exporter["xxhash"].xxh3_128_intdigest(b"").to_bytes(16, "little")))
    # Use each release architecture record without instantiating either model.
    body = bytearray(exporter["MAGIC"] + exporter["u32"](exporter["VERSION"])
                     + bytes(4) + bytes([2]) + bytes(7))
    for tower in towers:
        role = "query" if tower.role == 1 else "document"
        body += exporter["encode_tower"](tower, int(pair[role]["max_tokens"]))
    for tower in towers:
        body += exporter["encode_tokenizer"](tower.root, tower.architecture)
    body += struct.pack("<dI", 0.5, 0) + exporter["field"](b"tokenizer-parity")
    header_len = (len(body) + 4095) // 4096 * 4096
    body[12:16] = exporter["u32"](header_len)
    body += bytes(header_len - len(body))
    body += exporter["xxhash"].xxh3_128_intdigest(body).to_bytes(16, "little")
    output.write_bytes(body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack", type=Path, required=True)
    parser.add_argument("--query-sha", default=SOURCES["query"])
    parser.add_argument("--document-sha", default=SOURCES["document"])
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--rust-out", type=Path)
    target.add_argument("--fixture-out", type=Path)
    args = parser.parse_args()
    if args.rust_out:
        generate(args.pack, args.rust_out)
    else:
        fixture(args.pack, args.fixture_out, {"query": args.query_sha, "document": args.document_sha})


if __name__ == "__main__":
    main()
